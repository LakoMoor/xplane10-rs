import os
# gen_win10.py: Rendering Options (start_win 10, reno_class::reno_wind) as a widget table for
# the port, from the emulated call list (btnemu.py) and Resources/settings.txt (renpos.py).
import json, sys
sys.path.insert(0, '.')
from renpos import pos, settings
calls = json.load(open('out/reno/calls.json'))
S = settings(os.environ['XP_INSTALL'] + '/Resources/settings.txt')
# The binary numbers renopt_extended_dsf after renopt_detail_textures (oracle frame positions).
order = [s for s in S if s['name'] != 'renopt_extended_dsf']
order.insert(24, next(s for s in S if s['name'] == 'renopt_extended_dsf'))
rows = []
def row(kind, x, y, a='', b='', c='', d='', key='', label='', items='', cond=''):
    def f(v): return ('%g' % v) if isinstance(v, float) else str(v)
    rows.append('\t'.join(f(v) for v in (kind, x, y, a, b, c, d, key, label.replace('\t', ' '), items, cond)))
def lab(s): return s.split(' { ')[0] if isinstance(s, str) else ''
for c in calls:
    fn, xm, it, st = c['fn'], c['xmm'], c['int'], c['str']
    if fn.startswith('BTN_subwin'):
        r = c['rect']; row('subwin', r[0], r[1], r[2], r[3], it[0], key='', label=st[1] if isinstance(st[1], str) else '')
    elif fn.startswith('BTN_bool') and xm[0] is not None:
        key = {130.0: 'port:fullscreen', 610.0: {250.0: '_ios_sec_mon', 220.0: '_diff_FOV', 190.0: '_view_control', 160.0: '_window_2d_off'}}
        k = key.get(xm[0], ''); k = k.get(xm[1], '') if isinstance(k, dict) else k
        row('bool', xm[0], xm[1], key=k, label=lab(st[1]))
    elif fn.startswith('BTN_textlist') and xm[0] is not None:
        ok = lambda v: isinstance(v, str) and v != '?' and not v.startswith('stk')
        items = st[1] if ok(st[1]) else 'Default Monitor Settings'
        label = lab(st[2]) if ok(st[2]) else 'screen resolution | (only applies if the full-screen button is checked)'
        k = {(400.0, 690.0): '_tex_res', (400.0, 640.0): 'port:screen_res', (800.0, 690.0): 'port:vsync',
             (475.0, 360.0): '_aniso_filter', (475.0, 390.0): 'port:fsaa'}.get((xm[0], xm[1]), '')
        row('popup', xm[0], xm[1], key=k, label=label, items=items, cond='!renopt_HDR' if k == 'port:fsaa' else '')
    elif fn.startswith('BTN_flt_range'):
        row('flt', xm[0], xm[1], it[1], it[2], xm[2], xm[3], key='_screen_gamma_', label=lab(st[3]))
    elif fn.startswith('BTN_dob_range'):
        l = lab(st[3]); k = {(80.0, 250.0): '_off_lat_deg', (80.0, 200.0): '_off_vrt_deg', (80.0, 150.0): '_off_phi_deg',
            (280.0, 250.0): '_os_x_rat', (280.0, 200.0): '_os_y_rat', (490.0, 250.0): '_FOVx', (490.0, 200.0): '_FOVy'}[(xm[0], xm[1])]
        row('dob', xm[0], xm[1], it[1], it[2], xm[2], xm[3], key=k, label=l)
        if k == '_FOVy': rows[-1] += '_diff_FOV'
    elif fn.startswith('BTN_is_int'):
        row('radio', xm[0], xm[1], it[1], key='_default_view', label=lab(st[2]))
    elif fn.startswith('BTN_action'):
        row('action', xm[0], xm[1], xm[2], key='preset:' + st[2], label=st[2])
    elif fn.startswith('BTN_horz_slider') and xm[0] is not None:
        row('slider', xm[0], xm[1], xm[2], 0.0, 1.0, key='_cloud_pref_number_rat', label=lab(st[3]), items='cloudpct')
    elif fn.startswith('OGL_string') and isinstance(st[1], str) and st[1] not in ('?',) and not st[1].startswith('stk'):
        row('text', xm[0], xm[1], xm[2], it[0], label=st[1])
# The rendering settings loop: one widget per setting, at its switch position.
for i, s in enumerate(order):
    x, y = pos(i)
    kind = {'CHECK': 'bool', 'POPUP': 'popup', 'SLIDER': 'slider'}[s['ui']]
    req = 'renopt_HDR' if s['name'] in ('renopt_scattering', 'renopt_HDR_antial') else ''
    row(kind, float(x), float(y), cond=req, key=s['name'], label=s.get('label', ''), items=s.get('menu', '') if kind == 'popup' else '')
# Values the original fills in at run time.
row('text', 150.0, 95.0, 924.0, 56, key='gl:vendor')
row('text', 150.0, 85.0, 924.0, 56, key='gl:renderer')
row('text', 400.0, 85.0, 924.0, 56, key='gl:version')
row('text', 30.0, 35.0, 9999.0, 56, key='gl:texmem')
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../..') + '/crates/xp-core/data/windows/10.tsv'
open(out, 'w').write('# kind\tx\ty\ta\tb\tc\td\tkey\tlabel\titems\tcond (shown only when that pref is non-zero; ! negates) — Rendering Options (start_win 10), generated by\n# re/gen_win10.py from reno_class::reno_wind (0x10076b7a0) and Resources/settings.txt. x, y: GL window\n# coordinates (origin bottom-left) as passed to the BTN_* calls.\n# size 1020 766\n' + '\n'.join(rows) + '\n')
print(len(rows), 'rows')
