//! Golden tests for the apt.dat reader. Expectations come from
//! `tests/golden/aptdat/ksea_summary.txt`, extracted from shipped content.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use xp_core::aptdat::AptDat;

fn golden_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/golden")
}

fn read_golden(path: &Path) -> Result<BTreeMap<String, String>> {
    let text = std::fs::read_to_string(path)
        .with_context(|| format!("reading golden {}", path.display()))?;
    let mut out = BTreeMap::new();
    for line in text.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        // The golden uses "key = value" for per-file and per-runway entries and
        // "key: value" for the plain census; values may themselves contain spaces.
        let (k, v) = match line.find(" = ") {
            Some(i) => (&line[..i], &line[i + 3..]),
            None => match line.find(": ") {
                Some(i) => (&line[..i], &line[i + 2..]),
                None => bail!("{}: bad golden line {line:?}", path.display()),
            },
        };
        if k.trim().is_empty() || v.trim().is_empty() {
            bail!("{}: empty key or value in {line:?}", path.display());
        }
        out.insert(k.trim().to_string(), v.trim().to_string());
    }
    if out.is_empty() {
        bail!("golden {} is empty", path.display());
    }
    Ok(out)
}

#[test]
fn fixture_prefix_parses() -> Result<()> {
    let path = golden_dir().join("fixtures/ksea_prefix.aptdat");
    let a = AptDat::load(&path)?;
    assert_eq!(a.line_ending_marker, "I");
    assert_eq!(a.version, 1050);
    assert_eq!(a.generator, "Generated by WorldEditor");
    assert_eq!(a.airport_count(), 1);
    assert_eq!(a.preamble.len(), 0);
    let ksea = &a.airports[0];
    assert_eq!(ksea.seq(), Some(433));
    assert_eq!(ksea.name(), "KSEA Seattle Tacoma Intl");
    assert_eq!(ksea.icao().as_deref(), Some("KSEA"));
    // the prefix stops inside the first 110 group, so at least one runway and one path exist
    assert!(!ksea.runways.is_empty());
    assert!(!ksea.line_groups.is_empty());
    assert!(
        a.skipped_lines.is_empty(),
        "the prefix starts at a 1 record, so nothing may be orphaned: {:?}",
        a.skipped_lines
    );
    Ok(())
}

#[test]
fn ksea_matches_golden() -> Result<()> {
    let Some(root) = xp_core::install_root() else {
        eprintln!("SKIP ksea_matches_golden: XP_INSTALL unset (no coverage claimed)");
        return Ok(());
    };
    let rel = "Custom Scenery/KSEA Demo Area/Earth nav data/apt.dat";
    let path = root.join(rel);
    if !path.is_file() {
        eprintln!("SKIP ksea_matches_golden: {} missing", path.display());
        return Ok(());
    }
    let g = read_golden(&golden_dir().join("aptdat/ksea_summary.txt"))?;
    let a = AptDat::load(&path)?;

    assert_eq!(a.version, 1050);
    assert_eq!(a.airport_count(), 1);
    let ksea = &a.airports[0];
    assert_eq!(ksea.name(), g["ksea_airport_name"]);
    assert_eq!(
        ksea.seq().map(|v| v.to_string()),
        Some(g["ksea_airport_seq"].clone())
    );

    // every record type count in the census must reproduce
    let counts = a.record_counts();
    for (k, v) in &g {
        if let Some(t) = k
            .strip_prefix("ksea_record[")
            .and_then(|s| s.strip_suffix(']'))
        {
            let kind: u32 = t.parse()?;
            assert_eq!(
                counts.get(&kind).copied().unwrap_or(0),
                v.parse::<usize>()?,
                "record type {kind} count drifted"
            );
        }
    }
    assert_eq!(
        counts.len(),
        g.keys().filter(|k| k.starts_with("ksea_record[")).count()
    );

    // runways: field counts and the self-evident identity/coordinate fields
    assert_eq!(ksea.runways.len(), 3);
    for (i, r) in ksea.runways.iter().enumerate() {
        assert_eq!(
            r.record.fields.len(),
            g[&format!("ksea_runway[{i}].fields")].parse::<usize>()?
        );
        assert_eq!(
            r.record.field(1),
            Some(g[&format!("ksea_runway[{i}].field[1]")].as_str())
        );
        assert_eq!(
            r.end1_name(),
            Some(g[&format!("ksea_runway[{i}].end1_name")].as_str())
        );
        assert_eq!(
            r.end1_lat(),
            Some(g[&format!("ksea_runway[{i}].end1_lat")].parse::<f64>()?)
        );
        assert_eq!(
            r.end1_lon(),
            Some(g[&format!("ksea_runway[{i}].end1_lon")].parse::<f64>()?)
        );
        assert_eq!(
            r.end2_name(),
            Some(g[&format!("ksea_runway[{i}].end2_name")].as_str())
        );
        assert_eq!(
            r.end2_lat(),
            Some(g[&format!("ksea_runway[{i}].end2_lat")].parse::<f64>()?)
        );
        assert_eq!(
            r.end2_lon(),
            Some(g[&format!("ksea_runway[{i}].end2_lon")].parse::<f64>()?)
        );
    }
    assert_eq!(ksea.runways[0].identity(), "16L/34R");

    // adjacency grouping: no line record may be orphaned
    let lines_grouped: usize = ksea.line_groups.iter().map(|p| p.lines.len()).sum();
    let lines_total = counts.get(&111).copied().unwrap_or(0)
        + counts.get(&112).copied().unwrap_or(0)
        + counts.get(&113).copied().unwrap_or(0);
    assert_eq!(
        lines_grouped, lines_total,
        "every 111/112/113 must attach to a 110 group"
    );
    assert!(
        a.skipped_lines.is_empty(),
        "no record may be orphaned: {:?}",
        a.skipped_lines
    );
    Ok(())
}

/// All seven shipped apt.dat files must parse and reproduce their census numbers.
#[test]
fn every_shipped_apt_dat_parses() -> Result<()> {
    let Some(root) = xp_core::install_root() else {
        eprintln!("SKIP every_shipped_apt_dat_parses: XP_INSTALL unset (no coverage claimed)");
        return Ok(());
    };
    let g = read_golden(&golden_dir().join("aptdat/ksea_summary.txt"))?;
    let mut parsed = 0usize;
    for (k, want_sha) in &g {
        let Some(rel) = k
            .strip_prefix("file[")
            .and_then(|s| s.strip_suffix("].sha256"))
        else {
            continue;
        };
        let path = root.join(rel);
        if !path.is_file() {
            eprintln!("  missing {}: skipped, not passed", path.display());
            continue;
        }
        let a = AptDat::load(&path)?;
        parsed += 1;
        assert_eq!(
            hex(&sha256_of(&path)?),
            *want_sha,
            "{rel} changed since the golden was taken"
        );
        assert_eq!(
            a.version.to_string(),
            g[&format!("file[{rel}].version")],
            "{rel} version drifted"
        );
        assert_eq!(
            a.airport_count().to_string(),
            g[&format!("file[{rel}].airports")],
            "{rel} airport count drifted"
        );
        assert_eq!(
            a.all_records().len().to_string(),
            g[&format!("file[{rel}].records")],
            "{rel} record count drifted"
        );
        assert!(
            a.skipped_lines.is_empty(),
            "{rel} has {} orphaned records, e.g. {:?}",
            a.skipped_lines.len(),
            a.skipped_lines.iter().take(3).collect::<Vec<_>>()
        );
    }
    eprintln!("apt.dat files parsed: {parsed}");
    assert_eq!(parsed, g["file_count"].parse::<usize>()?);
    Ok(())
}

fn hex(bytes: &[u8; 32]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn sha256_of(path: &Path) -> Result<[u8; 32]> {
    let bytes = std::fs::read(path).with_context(|| format!("reading {}", path.display()))?;
    Ok(sha256_software(&bytes))
}

/// SHA-256 via the `sha2` dev-dependency, used only to prove the shipped files have not
/// changed since the goldens were extracted.
fn sha256_software(data: &[u8]) -> [u8; 32] {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(data);
    let mut a = [0u8; 32];
    a.copy_from_slice(&h.finalize());
    a
}

/// Guards the hash above: if this fails, every "unchanged since the golden was taken"
/// assertion in this file is meaningless.
#[test]
fn sha256_matches_a_published_vector() {
    assert_eq!(
        hex(&sha256_software(b"abc")),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
    assert_eq!(
        hex(&sha256_software(b"")),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
}
